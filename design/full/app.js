/* 三字读数 */
const H = (k, v, unit, notes) => ({ k, v, unit, notes: notes || [] })
/* 四格内嵌数据: [标签, 值, 语义色] */
const S4 = (...cells) => ({ t: 's4', cells })
/* 长条 / 梯队: [标签, 占比%, 值, 语义色|'hatch'] */
const BARS = (rows, label) => ({ t: 'bars', rows, label })
/* 名录: [名称, 次要信息, 值, 语义色] */
const LIST = (rows, cols) => ({ t: 'list', rows, cols: cols || 2 })
/* 表格 */
const TABLE = (head, rows) => ({ t: 'table', head, rows })
/* 表单行: [标签, 值, 动作] */
const FORM = (rows) => ({ t: 'form', rows })
/* 表单控件组: 一行一个控件, 共用一个 .form-rows 容器 */
const CTRL = rows => ({ t: 'ctrl', rows })
/* 段落 */
const NOTE = (text) => ({ t: 'note', text })

/* ---- 图形构件: 纯 SVG / CSS, 不引图表库 ---- */
/* 迷你走势线: 归一化到 96×28, 无坐标轴, 只表达方向 */
const SPARK = (series, tone, w) => ({ t: 'spark', series, tone: tone || '', w: w || 96 })
/* 柱状分布: [标签, 数量, 语义色] */
const HIST = (rows, label) => ({ t: 'hist', rows, label: label || '' })
/* 比例条: 三段占比 (跌, 平, 涨), 堆叠单行 */
const RATIO = (down, flat, up, label) => ({ t: 'ratio', down, flat, up, label: label || '' })
/* 雷达: [轴名, 0-100] */
const RADAR = (axes, score) => ({ t: 'radar', axes, score })
/* 热力矩阵: labels + 行列值 -1..1 或 null */
const HEAT = (labels, rows) => ({ t: 'heat', labels, rows })
/* K 线: [开, 高, 低, 收] */
const CANDLE = (bars, label) => ({ t: 'candle', bars, label: label || '' })
/* 阶梯进度: [阶段名, 完成度 0-1] */
const STEPS = (steps) => ({ t: 'steps', steps })
/* 日历热力: 只表达每日强度 0-4 */
const CAL = (cells, label) => ({ t: 'cal', cells, label: label || '' })
/* 环形进度 + 中心值 */
const GAUGE = (pct, center, label) => ({ t: 'gauge', pct, center, label: label || '' })


/* 时间点 + 条目 */
const E = (stamp, sub, title, en, body, opt) =>
  Object.assign({ stamp, sub, title, en, body: body || '', blocks: [] }, opt || {})

