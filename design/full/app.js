/* 折线: 值域归一化, 只表达方向与起伏, 不标刻度 */
function renderSpark(b) {
  const v = b.series.map(Number)
  if (v.length < 2) return ''
  const w = b.w, h = 28, pad = 2
  const min = Math.min(...v), max = Math.max(...v)
  const span = max - min || 1
  const pt = i => {
    const x = pad + (i / (v.length - 1)) * (w - pad * 2)
    const y = h - pad - ((v[i] - min) / span) * (h - pad * 2)
    return x.toFixed(1) + ',' + y.toFixed(1)
  }
  const line = v.map((_, i) => pt(i)).join(' ')
  const area = pad + ',0 ' + line + ' ' + (w - pad) + ',0'
  const stroke = b.tone === 'u' ? 'var(--up)' : b.tone === 'd' ? 'var(--down)' : 'var(--ink-3)'
  return '<svg class="spark" viewBox="0 0 ' + w + ' ' + h + '" width="' + w + '" height="' + h +
    '" aria-hidden="true"><polygon points="' + area + '" fill="' + stroke + '" opacity=".07"/>' +
    '<polyline points="' + line + '" fill="none" stroke="' + stroke + '" stroke-width="1.2" ' +
    'stroke-linejoin="round" stroke-linecap="round"/>' +
    '<circle cx="' + pt(v.length - 1).split(',')[0] + '" cy="' + pt(v.length - 1).split(',')[1] +
    '" r="1.8" fill="' + stroke + '"/></svg>'
}

