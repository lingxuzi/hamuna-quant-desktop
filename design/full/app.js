/* 雷达: 4-6 轴, 中心分数 */
function renderRadar(b) {
  const S = 180, c = S / 2, R = 62, n = b.axes.length
  if (!n) return ''
  const ang = i => -Math.PI / 2 + i * 2 * Math.PI / n
  const at = (i, rad) => [c + Math.cos(ang(i)) * rad, c + Math.sin(ang(i)) * rad]
  const ring = lv => b.axes.map((_, i) => at(i, R * lv).map(x => x.toFixed(1)).join(',')).join(' ')
  const body = b.axes.map((a, i) => {
    const v = Math.max(0, Math.min(100, a[1]))
    return at(i, R * v / 100).map(x => x.toFixed(1)).join(',')
  }).join(' ')
  return '<div class="radar"><svg viewBox="0 0 ' + S + ' ' + S + '" aria-label="' + esc(b.label || '多维评分') + '">' +
    [1, .66, .33].map(lv => '<polygon points="' + ring(lv) + '" fill="none" stroke="var(--rule)" stroke-width="' + (lv === 1 ? 1 : .6) + '"/>').join('') +
    b.axes.map((_, i) => '<line x1="' + c + '" y1="' + c + '" x2="' + at(i, R)[0].toFixed(1) + '" y2="' + at(i, R)[1].toFixed(1) + '" stroke="var(--rule)" stroke-width=".6"/>').join('') +
    '<polygon points="' + body + '" fill="var(--ochre)" fill-opacity=".16" stroke="var(--ochre)" stroke-width="1.2"/>' +
    b.axes.map((a, i) => {
      const p = at(i, R * Math.max(0, Math.min(100, a[1])) / 100)
      return '<circle cx="' + p[0].toFixed(1) + '" cy="' + p[1].toFixed(1) + '" r="2" fill="var(--ochre)"/>'
    }).join('') +
    b.axes.map((a, i) => {
      const p = at(i, R + 16)
      return '<text x="' + p[0].toFixed(1) + '" y="' + (p[1] + 3).toFixed(1) + '" text-anchor="middle" class="rd-l">' + esc(a[0]) + '</text>'
    }).join('') +
    (b.score != null ? '<text x="' + c + '" y="' + (c + 6) + '" text-anchor="middle" class="rd-s num">' + esc(b.score) + '</text>' : '') +
    '</svg></div>'
}

/* 热力矩阵: 行列相关度 -1..1, 零值白, 正赭石负墨绿 */
function renderHeat(b) {
  const cell = v => {
    if (v == null) return 'hatch'
    const a = Math.min(1, Math.abs(v))
    return (v >= 0 ? 'var(--ochre)' : 'var(--down)') + '|' + (a * .62).toFixed(2)
  }
  return '<table class="heat"><thead><tr><th></th>' +
    b.labels.map(l => '<th>' + esc(l) + '</th>').join('') + '</tr></thead><tbody>' +
    b.rows.map((row, i) => '<tr><th>' + esc(b.labels[i]) + '</th>' +
      row.map(v => {
        const cv = cell(v)
        const style = cv === 'hatch'
          ? 'background:repeating-linear-gradient(45deg,var(--fiber-strong) 0 3px,transparent 3px 7px)'
          : 'background:color-mix(in srgb,' + cv.split('|')[0] + ' ' + (+cv.split('|')[1] * 100) + '%,transparent)'
        return '<td style="' + style + '" title="' + (v == null ? '—' : v) + '">' +
          (v == null ? '' : '<span class="num">' + v.toFixed(2) + '</span>') + '</td>'
      }).join('') + '</tr>').join('') + '</tbody></table>'
}

/* K 线: 蜡烛 + 影线, 只表达形态 */
function renderCandle(b) {
  const n = b.bars.length
  if (!n) return ''
  const W = 560, H = 96, pad = 4
  const hi = Math.max(...b.bars.map(x => x[1])), lo = Math.min(...b.bars.map(x => x[2]))
  const span = hi - lo || 1
  const y = p => (H - pad - ((p - lo) / span) * (H - pad * 2)).toFixed(1)
  const step = W / n, cw = Math.max(2, step * .56)
  return '<div class="candle"><svg viewBox="0 0 ' + W + ' ' + H + '" role="img" aria-label="' +
    esc(b.label || 'K 线') + '" preserveAspectRatio="none">' + b.bars.map((bar, i) => {
    const [o, h, l, c] = bar
    const x = (i + .5) * step
    const col = c >= o ? 'var(--up)' : 'var(--down)'
    const top = y(Math.max(o, c)), bot = y(Math.min(o, c))
    return '<line x1="' + x.toFixed(1) + '" y1="' + y(h) + '" x2="' + x.toFixed(1) + '" y2="' + y(l) +
      '" stroke="' + col + '" stroke-width="1" vector-effect="non-scaling-stroke"/>' +
      '<rect x="' + (x - cw / 2).toFixed(1) + '" y="' + top + '" width="' + cw.toFixed(1) +
      '" height="' + Math.max(1.5, bot - top).toFixed(1) + '" fill="' + col + '"/>'
  }).join('') + '</svg></div>'
}

