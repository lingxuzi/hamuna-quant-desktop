/* ---------- 5. 渲染器 ---------- */
const esc = s => String(s == null ? '' : s).replace(/[&<>"]/g, c =>
  ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]))
const cls = c => (c ? ' ' + c : '')
/* 语义色只按首个符号判定, 日期与代码不受影响 */
const tone = v => {
  const s = String(v).trim()
  if (/^[+＋]/.test(s)) return 'u'
  if (/^[−-]/.test(s)) return 'd'
  return ''
}
